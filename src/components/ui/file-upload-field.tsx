"use client";

import { useState, useRef } from "react";
import { Button } from "@/components/ui/button";
import { Label } from "@/components/ui/label";
import { Upload, Loader2, X, FileText, Eye, RefreshCw } from "lucide-react";
import { withBasePath } from "@/lib/base-path";

interface FileUploadFieldProps {
  id: string;
  label: string;
  value: string;
  onChange: (path: string) => void;
  accept?: string;
  placeholder?: string;
  /** Upload API route — defaults to the shared /api/upload endpoint. */
  uploadEndpoint?: string;
}

/**
 * Display name for a stored document. The stored path itself is never
 * shown to users — only the basename. Uploads generated by the server
 * carry a "<timestamp>_" prefix, which is stripped for display.
 */
export function documentDisplayName(path: string): string {
  const base = decodeURIComponent(path.split(/[\\/]/).pop() ?? path);
  return base.replace(/^\d{9,}_/, "");
}

export function FileUploadField({
  id,
  label,
  value,
  onChange,
  accept = ".pdf,.jpg,.jpeg,.png,.doc,.docx",
  placeholder,
  uploadEndpoint = "/api/upload",
}: FileUploadFieldProps) {
  const [uploading, setUploading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);

  async function handleFileSelect(e: React.ChangeEvent<HTMLInputElement>) {
    const file = e.target.files?.[0];
    if (!file) return;

    setUploading(true);
    setError(null);

    try {
      const formData = new FormData();
      formData.append("file", file);
      formData.append("module", id);

      const res = await fetch(withBasePath(uploadEndpoint), {
        method: "POST",
        body: formData,
      });

      if (!res.ok) {
        const data = await res.json();
        throw new Error(data.error ?? "Upload failed");
      }

      const data = await res.json();
      onChange(data.path);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Upload failed");
    } finally {
      setUploading(false);
      if (fileInputRef.current) fileInputRef.current.value = "";
    }
  }

  const acceptHint = accept
    .split(",")
    .map((ext) => ext.replace(/^\./, "").toUpperCase())
    .join(", ");

  return (
    <div className="space-y-1.5">
      <Label htmlFor={id}>{label}</Label>
      <input
        ref={fileInputRef}
        type="file"
        accept={accept}
        onChange={handleFileSelect}
        className="hidden"
      />

      {value ? (
        <div className="flex items-center gap-2 rounded-lg border border-zinc-200 bg-zinc-50/60 px-3 py-2">
          <FileText className="h-4 w-4 shrink-0 text-blue-600" />
          <span
            className="min-w-0 flex-1 truncate text-sm font-medium text-zinc-800"
            title={documentDisplayName(value)}
          >
            {documentDisplayName(value)}
          </span>
          <a
            href={withBasePath(value)}
            target="_blank"
            rel="noopener noreferrer"
            title="View document"
          >
            <Button type="button" variant="outline" size="sm" className="h-7 gap-1 px-2 text-xs">
              <Eye className="h-3 w-3" />
              View
            </Button>
          </a>
          <Button
            type="button"
            variant="outline"
            size="sm"
            className="h-7 gap-1 px-2 text-xs"
            onClick={() => fileInputRef.current?.click()}
            disabled={uploading}
            title="Replace document"
          >
            {uploading ? (
              <Loader2 className="h-3 w-3 animate-spin" />
            ) : (
              <RefreshCw className="h-3 w-3" />
            )}
            Replace
          </Button>
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className="h-7 w-7 p-0 text-zinc-500 hover:text-zinc-700"
            onClick={() => onChange("")}
            title="Remove document"
          >
            <X className="h-3.5 w-3.5" />
          </Button>
        </div>
      ) : (
        <div className="flex items-center gap-2">
          <Button
            type="button"
            variant="outline"
            size="sm"
            id={id}
            onClick={() => fileInputRef.current?.click()}
            disabled={uploading}
            className="gap-1.5"
          >
            {uploading ? (
              <Loader2 className="h-3.5 w-3.5 animate-spin" />
            ) : (
              <Upload className="h-3.5 w-3.5" />
            )}
            Upload
          </Button>
          <span className="text-xs text-zinc-500">
            {placeholder ?? acceptHint}
          </span>
        </div>
      )}

      {error && <p className="text-xs text-red-600">{error}</p>}
    </div>
  );
}
