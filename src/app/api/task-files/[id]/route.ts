import { NextRequest, NextResponse } from "next/server";
import { readFile } from "fs/promises";
import path from "path";
import { auth } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import { canAccessTask } from "@/lib/task-access";

const UPLOAD_DIR = path.join(process.cwd(), "private_uploads");

export async function GET(
  _req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const session = await auth();
  if (!session?.user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const { id } = await params;
  const attachment = await prisma.taskAttachment.findUnique({
    where: { id },
    include: {
      task: {
        select: { assignedToId: true, assignedById: true, reviewerId: true },
      },
    },
  });
  if (!attachment) {
    return NextResponse.json({ error: "Not found" }, { status: 404 });
  }
  if (!(await canAccessTask(session.user, attachment.task))) {
    return NextResponse.json(
      { error: "You are not allowed to view this file" },
      { status: 403 }
    );
  }

  // The stored path was generated by our upload route; resolve it inside
  // the private upload dir only — never trust client-supplied paths.
  const abs = path.resolve(UPLOAD_DIR, attachment.path);
  if (!abs.startsWith(path.resolve(UPLOAD_DIR) + path.sep)) {
    return NextResponse.json({ error: "Invalid file path" }, { status: 400 });
  }

  try {
    const bytes = await readFile(abs);
    return new NextResponse(new Uint8Array(bytes), {
      headers: {
        "Content-Type": attachment.mimeType ?? "application/octet-stream",
        "Content-Disposition": `inline; filename="${attachment.filename.replace(/"/g, "_")}"`,
      },
    });
  } catch {
    return NextResponse.json({ error: "File not found on disk" }, { status: 404 });
  }
}
